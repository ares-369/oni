"""Zero-dependency Markdown-to-PDF generator for ONIOPS engagement reports.

Uses standard PDF 1.4 built-in Type1 fonts (Helvetica, Helvetica-Bold, Courier)
so every ONIOPS install (Docker, LXC, Windows, air-gapped) can export real PDF
files without external native libraries (wkhtmltopdf/libpango/reportlab).
"""
from __future__ import annotations

import re
import textwrap

PAGE_W = 595  # A4 width in points
PAGE_H = 842  # A4 height in points
MARGIN_X = 48
MARGIN_TOP = 54
MARGIN_BOTTOM = 52


def _pdf_escape(text: str) -> str:
    """Escape characters special in PDF literal strings and normalize to Latin-1."""
    clean = (
        text.replace("\u2014", "--")
        .replace("\u2013", "-")
        .replace("\u2018", "'")
        .replace("\u2019", "'")
        .replace("\u201c", '"')
        .replace("\u201d", '"')
        .replace("\u2022", "*")
        .replace("\u2192", "->")
    )
    clean = clean.encode("latin-1", errors="replace").decode("latin-1")
    return clean.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _strip_inline_md(line: str) -> str:
    line = re.sub(r"\*\*(.+?)\*\*", r"\1", line)
    line = re.sub(r"`([^`]+)`", r"\1", line)
    return line


def markdown_to_pdf(markdown_text: str, title: str = "ONIOPS Security Assessment Report") -> bytes:
    """Render Markdown text into a multi-page A4 PDF document."""
    lines_spec: list[tuple[str, int, int, str]] = []
    # Tuple: (font_key, font_size, leading, text)
    # F1 = Helvetica, F2 = Helvetica-Bold, F3 = Courier

    if title:
        lines_spec.append(("F2", 16, 22, title.strip()))
        lines_spec.append(("F1", 9, 16, "Generated by ONIOPS (Offensive Neural Intelligence)"))
        lines_spec.append(("F1", 10, 10, ""))

    in_code = False
    for raw in (markdown_text or "").splitlines():
        stripped = raw.strip()
        if stripped.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            wrapped = textwrap.wrap(raw, width=82, replace_whitespace=False, drop_whitespace=False) or [""]
            for w in wrapped:
                lines_spec.append(("F3", 8, 11, w))
            continue

        if not stripped:
            lines_spec.append(("F1", 10, 8, ""))
            continue

        if stripped.startswith("# "):
            heading = _strip_inline_md(stripped[2:].strip())
            for w in textwrap.wrap(heading, width=62) or [heading]:
                lines_spec.append(("F2", 14, 20, w))
        elif stripped.startswith("## "):
            heading = _strip_inline_md(stripped[3:].strip())
            lines_spec.append(("F1", 10, 6, ""))
            for w in textwrap.wrap(heading, width=68) or [heading]:
                lines_spec.append(("F2", 12, 17, w))
        elif stripped.startswith("### "):
            heading = _strip_inline_md(stripped[4:].strip())
            for w in textwrap.wrap(heading, width=74) or [heading]:
                lines_spec.append(("F2", 10, 15, w))
        elif stripped.startswith(("- ", "* ")):
            item = _strip_inline_md(stripped[2:].strip())
            wrapped = textwrap.wrap(item, width=78) or [item]
            for idx, w in enumerate(wrapped):
                prefix = "  * " if idx == 0 else "    "
                lines_spec.append(("F1", 10, 14, prefix + w))
        else:
            body = _strip_inline_md(stripped)
            for w in textwrap.wrap(body, width=82) or [body]:
                lines_spec.append(("F1", 10, 14, w))

    # Paginate into page content streams
    pages_ops: list[str] = []
    cur_ops: list[str] = []
    y = PAGE_H - MARGIN_TOP

    def _flush_page(page_num: int) -> None:
        nonlocal cur_ops, y
        footer = f"BT /F1 8 Tf {MARGIN_X} 28 Td (ONIOPS Report - Page {page_num}) Tj ET"
        cur_ops.append(footer)
        pages_ops.append("\n".join(cur_ops))
        cur_ops = []
        y = PAGE_H - MARGIN_TOP

    for font_key, size, leading, text in lines_spec:
        if y - leading < MARGIN_BOTTOM:
            _flush_page(len(pages_ops) + 1)
        y -= leading
        if text:
            esc = _pdf_escape(text)
            cur_ops.append(f"BT /{font_key} {size} Tf {MARGIN_X} {y} Td ({esc}) Tj ET")

    if cur_ops or not pages_ops:
        _flush_page(len(pages_ops) + 1)

    # Assemble PDF objects
    # 1: Catalog, 2: Pages, 3: F1 (Helvetica), 4: F2 (Helvetica-Bold), 5: F3 (Courier)
    objects: list[bytes] = []

    def _add_obj(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    _add_obj(b"<< /Type /Catalog /Pages 2 0 R >>")
    _add_obj(b"")  # placeholder for Pages
    _add_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    _add_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    _add_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>")

    page_ids: list[int] = []
    for stream_str in pages_ops:
        stream_bytes = stream_str.encode("latin-1")
        content_id = _add_obj(
            f"<< /Length {len(stream_bytes)} >>\nstream\n".encode("ascii")
            + stream_bytes
            + b"\nendstream"
        )
        page_id = _add_obj(
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W} {PAGE_H}] "
            f"/Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> "
            f"/Contents {content_id} 0 R >>".encode("ascii")
        )
        page_ids.append(page_id)

    kids = " ".join(f"{pid} 0 R" for pid in page_ids)
    objects[1] = f"<< /Type /Pages /Kids [{kids}] /Count {len(page_ids)} >>".encode("ascii")

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets: list[int] = [0]
    for i, obj in enumerate(objects, start=1):
        offsets.append(len(out))
        out.extend(f"{i} 0 obj\n".encode("ascii"))
        out.extend(obj)
        out.extend(b"\nendobj\n")

    xref_pos = len(out)
    out.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    out.extend(b"0000000000 65535 f \n")
    for off in offsets[1:]:
        out.extend(f"{off:010d} 00000 n \n".encode("ascii"))
    out.extend(
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode(
            "ascii"
        )
    )
    return bytes(out)
